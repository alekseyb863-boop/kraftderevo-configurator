// V006-2 (В006-2) Открытая вешалка-рейл: вертикальная рамка (две стойки + верхняя перекладина) на напольной рамке-основании. Профиль квадратный (по умолчанию 25×25). мм, Z вверх, начало в углу основания.
//
// РАЗМЕРЫ (названия и порядок как на сайте «150×80×40 см» = Высота × Ширина × Глубина; чертёж с сайта: 1500 / 800 / 400):
//   H «Высота» — полная высота рейла от пола до верха перекладины;  W «Ширина» — длина перекладины = габарит по X;  D «Глубина» — размер основания по Y.
// ГЕОМЕТРИЯ (по фото и эскизу с сайта; a — сторона профиля):
//   Основание: кольцо из 4 профилей на полу, внешний контур W × D, высота a (z ∈ [0, a]); внутри пусто (на фото видно пол, полки нет).
//   Вертикальная рамка стоит в плоскости, проходящей по СЕРЕДИНЕ глубины основания (y ∈ [(D − a)/2, (D + a)/2]); стойки стоят на коротких сторонах основания
//   вровень с его внешними гранями x ∈ [0, a] и [W − a, W], z ∈ [a, H]; перекладина x ∈ [a, W − a], z ∈ [H − a, H] (верх вровень со стойками, углы острые).
//   Нижней перемычки в вертикальной рамке нет. Всё сливается в ОДНО тело (fuseAll + simplify).
import { box } from "../lib/model.js";
import { SQUARES, range, profileCtl, colorCtl, findIn, baseNormalize } from "../lib/params.js";
import { dimAB } from "../render/dimhelpers.js";

const controls = [range("H", "Высота", 500, 2200, 10, 1500), range("W", "Ширина", 300, 2000, 10, 800), range("D", "Глубина", 200, 1000, 10, 400),
  profileCtl("25x25", "profile", "Профиль", SQUARES), colorCtl("черный")];
const prof = (p) => findIn(SQUARES, p.profile);
export const spec = {
  id: "V006-2", type: "Рейл", name: "Рейл В006-2", about: "Открытая вешалка-рейл: вертикальная рамка на напольной рамке-основании", controls,
  normalize(raw) { const { p, warnings } = baseNormalize(controls, raw); return { p, warnings }; },
  parts(p) {
    const a = prof(p).a, { H, W, D } = p, yc0 = (D - a) / 2, yc1 = (D + a) / 2;
    return [box(0, W, 0, a, 0, a), box(0, W, D - a, D, 0, a), box(0, a, a, D - a, 0, a), box(W - a, W,  a, D - a, 0, a),   // основание
      box(0, a, yc0, yc1, a, H), box(W - a, W, yc0, yc1, a, H), box(a, W - a, yc0, yc1, H - a, H)];                        // стойки + перекладина
  },
  expectBBox: (p) => [p.W, p.D, p.H],
  view: { az: 35, el: 16 }, layout: "forms", auto: true,
  dims(p, k = 1) {
    const { H, W, D } = p, O = 90 * k;
    return [dimAB([0, 0, 0], [W, 0, 0], [0, -O, 0], [W, -O, 0], `${W} мм`), dimAB([0, 0, 0], [0, 0, H], [-O, 0, 0], [-O, 0, H], `${H} мм`),
      dimAB([W, 0, 0], [W, D, 0], [W + O, 0, 0], [W + O, D, 0], `${D} мм`)];
  },
  textLines: (p) => ["Рейл В006-2", `Профиль ${prof(p).label} мм`, `Цвет: ${p.color}`, `Высота: ${p.H} мм`, `Ширина: ${p.W} мм`, `Глубина: ${p.D} мм`],
};
