// V004 (В004) Открытая вешалка для прихожей: каркас-параллелепипед W × D × H из квадратного профиля (по умолчанию 25×25): 4 стойки по углам, нижнее кольцо из 4 профилей,
// сверху — два коротких профиля по глубине на концах и перекладина-штанга вдоль ширины по середине глубины («Н»-образный верх). мм, Z вверх, начало в углу.
//
// РАЗМЕРЫ (как на сайте «150×80×40 см» = Высота × Ширина × Глубина; эскиз с сайта: 1500 / 800 / 400):  H «Высота» (пол — верх), W «Ширина» (по X, вдоль штанги), D «Глубина» (по Y).
// ГЕОМЕТРИЯ (a — сторона профиля; все внешние грани вровень, углы острые, ничего не торчит):
//   Стойки: 4 шт., x ∈ [0, a] / [W − a, W], y ∈ [0, a] / [D − a, D], z ∈ [0, H].
//   Низ (z ∈ [0, a]): передний/задний профили x ∈ [a, W − a] и боковые x ∈ [0, a] / [W − a, W] на всю глубину y ∈ [0, D] — кольцо; перемычек внутри нет (на фото видно пол).
//   Верх (z ∈ [H − a, H]): боковые профили по глубине x ∈ [0, a] / [W − a, W], y ∈ [0, D]; штанга x ∈ [a, W − a], y ∈ [(D − a)/2, (D + a)/2] — соединяет середины боковых профилей.
//   Передней/задней верхних перекладин нет (по фото: штанга одна). Всё сливается в ОДНО тело (fuseAll + simplify).
import { box } from "../lib/model.js";
import { SQUARES, range, profileCtl, colorCtl, findIn, baseNormalize } from "../lib/params.js";
import { dimAB } from "../render/dimhelpers.js";

const controls = [range("H", "Высота", 500, 2200, 10, 1500), range("W", "Ширина", 300, 2000, 10, 800), range("D", "Глубина", 200, 1000, 10, 400),
  profileCtl("25x25", "profile", "Профиль", SQUARES), colorCtl("черный")];
const prof = (p) => findIn(SQUARES, p.profile);
export const spec = {
  id: "V004", type: "Рейл", category: "Рейлы", name: "Рейл В004", about: "Открытая вешалка для прихожей: каркас-параллелепипед со штангой наверху", controls,
  normalize(raw) { const { p, warnings } = baseNormalize(controls, raw); return { p, warnings }; },
  parts(p) {
    const a = prof(p).a, { H, W, D } = p, yc0 = (D - a) / 2, yc1 = (D + a) / 2, out = [];
    for (const [x0, x1] of [[0, a], [W - a, W]]) {
      for (const [y0, y1] of [[0, a], [D - a, D]]) out.push(box(x0, x1, y0, y1, 0, H));      // 4 стойки
      out.push(box(x0, x1, a, D - a, 0, a), box(x0, x1, a, D - a, H - a, H));                  // нижний и верхний боковые профили (по глубине)
    }
    out.push(box(a, W - a, 0, a, 0, a), box(a, W - a, D - a, D, 0, a));                       // нижние передний и задний
    out.push(box(a, W - a, yc0, yc1, H - a, H));                                                // штанга
    return out;
  },
  expectBBox: (p) => [p.W, p.D, p.H],
  view: { az: 35, el: 16 }, layout: "forms", auto: true,
  dims(p, k = 1) {
    const { H, W, D } = p, O = 125 * k;
    return [dimAB([0, 0, 0], [W, 0, 0], [0, -O, 0], [W, -O, 0], `${W} мм`), dimAB([0, 0, 0], [0, 0, H], [-O, 0, 0], [-O, 0, H], `${H} мм`),
      dimAB([W, 0, 0], [W, D, 0], [W + O, 0, 0], [W + O, D, 0], `${D} мм`)];
  },
  textLines: (p) => ["Рейл В004", `Профиль ${prof(p).label} мм`, `Цвет: ${p.color}`, `Высота: ${p.H} мм`, `Ширина: ${p.W} мм`, `Глубина: ${p.D} мм`],
};
