// Номер заказа на чертеже: крупный заголовок «Заказ <номер>» над текстовым блоком (название артикула становится обычной строкой).
/** текст поля -> заголовок или "" (пусто — заголовка нет); если пользователь уже написал «Заказ …», текст не дублируется */
export function orderTitle(raw) {
  const s = String(raw ?? "").trim().replace(/\s+/g, " ").slice(0, 40);
  if (!s) return "";
  return /^заказ(\s|$|[№#:])/i.test(s) ? s : `Заказ ${s}`;
}
/** строки текстового блока с заголовком заказа (первая строка — крупная жирная, остальные — обычные) */
export const withOrder = (lines, raw) => { const t = orderTitle(raw); return t ? [t, ...lines] : lines; };
